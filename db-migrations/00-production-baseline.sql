-- JobWest production baseline for a fresh Supabase project.
-- Run this before importing real ads or enabling payments.

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;
CREATE SCHEMA IF NOT EXISTS private;

CREATE TABLE IF NOT EXISTS public.users (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text UNIQUE,
  name text,
  image text,
  role text NOT NULL DEFAULT 'employer' CHECK (role IN ('employer', 'admin', 'owner')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  company text,
  contact_info text,
  title text NOT NULL,
  description text,
  category text NOT NULL,
  country_code text NOT NULL,
  location text,
  salary text NOT NULL,
  job_type text NOT NULL,
  accommodation_provided boolean NOT NULL DEFAULT false,
  accommodation_included boolean NOT NULL DEFAULT false,
  accommodation_paid boolean NOT NULL DEFAULT false,
  is_top boolean NOT NULL DEFAULT false,
  highlight_tier text NOT NULL DEFAULT 'standard' CHECK (highlight_tier IN ('standard', 'top', 'exclusive')),
  topped_at timestamptz,
  portal_code text NOT NULL DEFAULT 'sk',
  portal_domain text NOT NULL DEFAULT 'jobwest.sk',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  job_id bigint REFERENCES public.jobs(id) ON DELETE SET NULL,
  stripe_session_id text UNIQUE,
  tier text NOT NULL CHECK (tier IN ('top', 'exclusive', 'add-ad')),
  amount_cents integer NOT NULL,
  currency text NOT NULL DEFAULT 'eur',
  status text NOT NULL DEFAULT 'pending',
  portal_code text NOT NULL DEFAULT 'sk',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS users_role_idx ON public.users(role);
CREATE INDEX IF NOT EXISTS jobs_user_id_idx ON public.jobs(user_id);
CREATE INDEX IF NOT EXISTS jobs_portal_code_idx ON public.jobs(portal_code);
CREATE INDEX IF NOT EXISTS jobs_country_created_at_idx ON public.jobs(country_code, created_at DESC);
CREATE INDEX IF NOT EXISTS jobs_highlight_sort_idx ON public.jobs(highlight_tier, topped_at DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS payments_portal_code_idx ON public.payments(portal_code);
CREATE INDEX IF NOT EXISTS payments_user_id_idx ON public.payments(user_id);
CREATE INDEX IF NOT EXISTS payments_status_created_at_idx ON public.payments(status, created_at DESC);

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'avatars',
  'avatars',
  true,
  2097152,
  ARRAY['image/jpeg', 'image/png', 'image/gif']
)
ON CONFLICT (id) DO UPDATE
SET
  public = EXCLUDED.public,
  file_size_limit = EXCLUDED.file_size_limit,
  allowed_mime_types = EXCLUDED.allowed_mime_types;

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON public.jobs TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.jobs TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.jobs_id_seq TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.users TO authenticated;
GRANT SELECT ON public.payments TO authenticated;

CREATE OR REPLACE FUNCTION private.is_jobwest_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.users
    WHERE users.id = auth.uid()
      AND users.role IN ('admin', 'owner')
  );
$$;

REVOKE ALL ON FUNCTION private.is_jobwest_admin() FROM PUBLIC;
GRANT USAGE ON SCHEMA private TO authenticated;
GRANT EXECUTE ON FUNCTION private.is_jobwest_admin() TO authenticated;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'jobs'
      AND policyname = 'Public can read job ads'
  ) THEN
    CREATE POLICY "Public can read job ads"
    ON public.jobs
    FOR SELECT
    USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'jobs'
      AND policyname = 'Employers can create own jobs'
  ) THEN
    CREATE POLICY "Employers can create own jobs"
    ON public.jobs
    FOR INSERT
    TO authenticated
    WITH CHECK ((select auth.uid()) = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'jobs'
      AND policyname = 'Employers can update own jobs'
  ) THEN
    CREATE POLICY "Employers can update own jobs"
    ON public.jobs
    FOR UPDATE
    TO authenticated
    USING ((select auth.uid()) = user_id)
    WITH CHECK ((select auth.uid()) = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'jobs'
      AND policyname = 'Employers can delete own jobs'
  ) THEN
    CREATE POLICY "Employers can delete own jobs"
    ON public.jobs
    FOR DELETE
    TO authenticated
    USING ((select auth.uid()) = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'users'
      AND policyname = 'Users can read own profile'
  ) THEN
    CREATE POLICY "Users can read own profile"
    ON public.users
    FOR SELECT
    TO authenticated
    USING ((select auth.uid()) = id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'users'
      AND policyname = 'Users can create own profile'
  ) THEN
    CREATE POLICY "Users can create own profile"
    ON public.users
    FOR INSERT
    TO authenticated
    WITH CHECK ((select auth.uid()) = id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'users'
      AND policyname = 'Users can update own profile'
  ) THEN
    CREATE POLICY "Users can update own profile"
    ON public.users
    FOR UPDATE
    TO authenticated
    USING ((select auth.uid()) = id)
    WITH CHECK ((select auth.uid()) = id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'payments'
      AND policyname = 'Users can read own payments'
  ) THEN
    CREATE POLICY "Users can read own payments"
    ON public.payments
    FOR SELECT
    TO authenticated
    USING ((select auth.uid()) = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'jobs'
      AND policyname = 'Admins can read all jobs'
  ) THEN
    CREATE POLICY "Admins can read all jobs"
    ON public.jobs
    FOR SELECT
    TO authenticated
    USING (private.is_jobwest_admin());
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'payments'
      AND policyname = 'Admins can read all payments'
  ) THEN
    CREATE POLICY "Admins can read all payments"
    ON public.payments
    FOR SELECT
    TO authenticated
    USING (private.is_jobwest_admin());
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'users'
      AND policyname = 'Admins can read users'
  ) THEN
    CREATE POLICY "Admins can read users"
    ON public.users
    FOR SELECT
    TO authenticated
    USING (private.is_jobwest_admin());
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'storage'
      AND tablename = 'objects'
      AND policyname = 'Public can read avatars'
  ) THEN
    CREATE POLICY "Public can read avatars"
    ON storage.objects
    FOR SELECT
    USING (bucket_id = 'avatars');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'storage'
      AND tablename = 'objects'
      AND policyname = 'Users can upload own avatars'
  ) THEN
    CREATE POLICY "Users can upload own avatars"
    ON storage.objects
    FOR INSERT
    TO authenticated
    WITH CHECK (
      bucket_id = 'avatars'
      AND (storage.foldername(name))[1] = (select auth.uid())::text
    );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'storage'
      AND tablename = 'objects'
      AND policyname = 'Users can update own avatars'
  ) THEN
    CREATE POLICY "Users can update own avatars"
    ON storage.objects
    FOR UPDATE
    TO authenticated
    USING (
      bucket_id = 'avatars'
      AND (storage.foldername(name))[1] = (select auth.uid())::text
    )
    WITH CHECK (
      bucket_id = 'avatars'
      AND (storage.foldername(name))[1] = (select auth.uid())::text
    );
  END IF;
END $$;
